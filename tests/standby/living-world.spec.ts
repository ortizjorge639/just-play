test("world context loss safely releases the canvas and keeps accessible records", async ({ page }) => {
  await page.goto("/?app-shell&residents")
  await page.getByRole("button", { name: "Home", exact: true }).click()
  const scene = page.getByTestId("settlement-3d")
  await expect(scene).toHaveAttribute("data-state", "ready")
  await expect(scene).toHaveAttribute("data-render-state", "reduced-motion")
  await scene.locator("canvas").evaluate(el => el.dispatchEvent(new Event("webglcontextlost", { cancelable: true })))
  await expect(scene).toHaveCount(0)
  await expect(page.getByRole("region", { name: "Deck 1" })).toBeVisible()
  await page.getByText("Residents & archive", { exact: true }).click()
  await expect(page.getByRole("heading", { name: "Lives here" })).toBeVisible()
})
