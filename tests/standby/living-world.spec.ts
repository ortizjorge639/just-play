import { test, expect } from "@playwright/test"

test.use({ reducedMotion: "reduce" })

test("Home opens directly into the shared world, including an empty home", async ({ page }) => {
  await page.goto("/?app-shell")
  await page.getByRole("button", { name: "Home", exact: true }).click()
  await expect(page.getByRole("region", { name: "Your home", exact: true })).toBeVisible()
  await expect(page.getByText("Games you finish will live here.")).toBeVisible()
  await expect(page.getByRole("button", { name: "List", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Settlement", exact: true })).toHaveCount(0)
  await expect(page.getByRole("heading", { name: "Lives here" })).not.toBeVisible()
})

test("StandBy shares Home residents without nesting a settlement dialog and keeps session controls", async ({ page }) => {
  await page.goto("/?app-shell&residents")
  await page.getByRole("button", { name: "Home", exact: true }).click()
  const scene = page.getByTestId("settlement-3d")
  await expect(scene).toHaveAttribute("data-state", "ready")
  const figures = await scene.getAttribute("data-figures")
  await page.getByRole("button", { name: "Now Playing", exact: true }).click()
  await page.getByRole("button", { name: /Enter StandBy/ }).click()
  await expect(page.getByRole("dialog")).toHaveCount(1)
  await expect(page.getByTestId("settlement-3d")).toHaveAttribute("data-figures", figures!)
  await page.getByRole("button", { name: "Pause", exact: true }).click()
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled()
  await page.getByRole("combobox", { name: "StandBy view" }).selectOption("artwork")
  await expect(scene).toHaveCount(0)
  await page.getByRole("combobox", { name: "StandBy view" }).selectOption("world")
  await expect(scene).toHaveCount(1)
  await page.getByRole("button", { name: "Exit StandBy", exact: true }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
})

for (const size of [{width:320,height:568},{width:390,height:844},{width:844,height:390},{width:1280,height:800}]) {
  test(`shared world controls remain reachable at ${size.width}x${size.height} with failed art`, async ({ page }) => {
    await page.setViewportSize(size)
    await page.route("**/canopy/*.glb", route => route.abort())
    await page.goto("/?app-shell&residents")
    await page.getByRole("button", { name: /Enter StandBy/ }).click()
    await expect(page.getByRole("region", { name: "Deck 1" })).toBeVisible()
    const dialog = page.getByRole("dialog")
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await expect(page.getByRole("button", { name: "Pause", exact: true })).toBeInViewport()
    await expect(page.getByRole("button", { name: "Exit StandBy", exact: true })).toBeInViewport()
    await page.getByRole("button", { name: "Session details", exact: true }).click()
    await expect(page.getByRole("region", { name: "Session context" })).toBeFocused()
    await page.getByRole("button", { name: "Hide session details", exact: true }).click()
    await expect(page.getByRole("button", { name: "Hide session details", exact: true })).toHaveCount(0)
    await page.getByRole("button", { name: "Exit StandBy", exact: true }).click()
  })
}

test("shared world is quiet by default and offers a live sound toggle on both surfaces", async ({ page }) => {
  await page.goto("/?app-shell&residents")
  await page.getByRole("button", { name: "Home", exact: true }).click()
  const sound = page.getByRole("button", { name: "World sound", exact: true })
  await expect(sound).toHaveAttribute("aria-pressed", "false")
  await sound.click()
  await expect(sound).toHaveAttribute("aria-pressed", "true")
  await page.getByRole("button", { name: "Now Playing", exact: true }).click()
  await page.getByRole("button", { name: /Enter StandBy/ }).click()
  await expect(sound).toHaveAttribute("aria-pressed", "true")
  await sound.click()
  await expect(sound).toHaveAttribute("aria-pressed", "false")
  expect(await page.evaluate(() => localStorage.getItem("jp-settlement-sound"))).toBe("off")
})

for (const persisted of ["on", "off"]) {
  test(`sound choice survives write-only storage failure with saved ${persisted}`, async ({ page }) => {
    await page.addInitScript(saved => {
      localStorage.setItem("jp-settlement-sound", saved)
      Storage.prototype.setItem = () => { throw new DOMException("Quota exceeded", "QuotaExceededError") }
    }, persisted)
    await page.route("**/canopy/*.glb", route => route.abort())
    await page.goto("/?app-shell&residents")
    await page.getByRole("button", { name: "Home", exact: true }).click()
    const sound = page.getByRole("button", { name: "World sound", exact: true })
    await expect(sound).toHaveAttribute("aria-pressed", String(persisted === "on"))
    await sound.click()
    await expect(sound).toHaveAttribute("aria-pressed", String(persisted !== "on"))
    await page.getByRole("button", { name: "Now Playing", exact: true }).click()
    await page.getByRole("button", { name: /Enter StandBy/ }).click()
    await expect(sound).toHaveAttribute("aria-pressed", String(persisted !== "on"))
    await sound.click()
    await expect(sound).toHaveAttribute("aria-pressed", String(persisted === "on"))
    expect(await page.evaluate(() => localStorage.getItem("jp-settlement-sound"))).toBe(persisted)
  })
}

test("StandBy resident inspection works from the keyboard and restores focus", async ({ page }) => {
  await page.goto("/?app-shell&residents")
  await page.getByRole("button", { name: /Enter StandBy/ }).click()
  const picker = page.getByRole("combobox", { name: "Inspect resident" })
  await expect(picker).toBeVisible()
  await picker.focus()
  await picker.press("ArrowDown")
  await expect(page.getByRole("button", { name: /Say hi to/ })).toBeVisible()
  await page.keyboard.press("Tab")
  await expect(page.getByRole("button", { name: "World sound", exact: true })).toBeFocused()
  await page.keyboard.press("Tab")
  const close = page.getByRole("button", { name: "Close resident", exact: true })
  await expect(close).toBeFocused()
  await close.press("Enter")
  await expect(picker).toBeFocused()
  await expect(close).toHaveCount(0)
})

